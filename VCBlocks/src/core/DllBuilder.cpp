std::string DllBuilder::ApiName(const Options& opt) {
    std::string n;
    for (char c : opt.dllName) {
        n += ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_') ? c : '_';
    }
    if (n.empty()) n = "plugin";
    if (n[0] >= '0' && n[0] <= '9') n = "p" + n;
    return n + "_run";
}

std::string DllBuilder::GenerateSource(const Program& p, const Options& opt, std::string& err) {
    std::vector<std::string> vars;
    std::string body = CodeGenerator::GenerateBody(p, vars, err);
    std::string apiName = ApiName(opt);
    std::string ns = opt.jsNamespace.empty() ? "blocks" : opt.jsNamespace;
    std::string desc = opt.description.empty() ? ("Generated by VCBlocks for " + p.name) : opt.description;
    std::string panelId = "com.vcblocks." + (opt.dllName.empty() ? "plugin" : opt.dllName);
    std::string panelTitle = opt.panelTitle.empty() ? opt.dllName : opt.panelTitle;
    std::string panelIcon = opt.panelIcon.empty() ? "\xE2\x9C\xA8" : opt.panelIcon;
    std::string panelClass = "VCBlocksPanel_" + (opt.dllName.empty() ? "plugin" : opt.dllName);

    std::string src;
    src += "/* Auto-generated by VCBlocks — light GUI plugin (YXG ABI v1) */\n";
    src += "#define YXG_BUILD_DLL\n";
    src += kYxgAbi;
    src += "\n#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\n";

    src += "static YXG_ExtensionApi* g_api = 0;\n\n";

    src += "static void vbc_log_text(const char* s) {\n";
    src += "    if (!g_api || !g_api->LogInfo || !s) return;\n";
    src += "    wchar_t buf[2048];\n";
    src += "    mbstowcs(buf, s, 2047);\n";
    src += "    g_api->LogInfo(buf);\n";
    src += "}\n";
    src += "static void vbc_log_num(int n) {\n";
    src += "    char b[64];\n";
    src += "    snprintf(b, sizeof(b), \"%d\", n);\n";
    src += "    vbc_log_text(b);\n";
    src += "}\n\n";
    src += "#define VBC_PRINT_TEXT(s) vbc_log_text(s)\n";
    src += "#define VBC_PRINT_NUM(n) vbc_log_num((int)(n))\n\n";

    src += "static int vbc_run(void) {\n";
    for (const auto& v : vars) {
        src += "    int " + v + " = 0;\n";
    }
    if (!vars.empty()) src += "\n";
    src += body;
    src += "    return 0;\n";
    src += "}\n\n";

    src += "static void vbc_api_" + apiName + "(YXG_PluginContext* ctx, int argc, YXG_JSValue* argv, YXG_JSValue* ret) {\n";
    src += "    (void)ctx; (void)argc; (void)argv;\n";
    src += "    int r = vbc_run();\n";
    src += "    if (g_api && g_api->JSValueSetInt) g_api->JSValueSetInt(ret, r);\n";
    src += "}\n\n";

    // ---- 原生面板（light 侧边栏新 Tab） ----
    src += "static LRESULT CALLBACK vbc_panel_proc(HWND h, UINT m, WPARAM w, LPARAM l) {\n";
    src += "    if (m == WM_COMMAND && LOWORD(w) == 1001) { vbc_run(); return 0; }\n";
    src += "    return DefWindowProcW(h, m, w, l);\n";
    src += "}\n\n";
    src += "static HWND vbc_create_panel(YXG_PluginContext* ctx, HWND parent) {\n";
    src += "    (void)ctx;\n";
    src += "    HINSTANCE inst = GetModuleHandleW(NULL);\n";
    src += "    static int regged = 0;\n";
    src += "    if (!regged) {\n";
    src += "        WNDCLASSW wc; memset(&wc, 0, sizeof(wc));\n";
    src += "        wc.lpfnWndProc = vbc_panel_proc;\n";
    src += "        wc.hInstance = inst;\n";
    src += "        wc.lpszClassName = L\"" + EscapeCString(panelClass) + "\";\n";
    src += "        wc.hbrBackground = (HBRUSH)GetStockObject(WHITE_BRUSH);\n";
    src += "        RegisterClassW(&wc);\n";
    src += "        regged = 1;\n";
    src += "    }\n";
    src += "    HWND h = CreateWindowExW(0, L\"" + EscapeCString(panelClass) + "\", L\"\", WS_CHILD | WS_VISIBLE, 0, 0, 100, 100, parent, NULL, inst, NULL);\n";
    src += "    if (!h) return NULL;\n";
    src += "    CreateWindowExW(0, L\"STATIC\", L\"" + EscapeCString(panelTitle) + "\", WS_CHILD | WS_VISIBLE, 24, 24, 620, 40, h, (HMENU)100, inst, NULL);\n";
    src += "    CreateWindowExW(0, L\"STATIC\", L\"" + EscapeCString(desc) + "\", WS_CHILD | WS_VISIBLE, 24, 72, 620, 60, h, (HMENU)101, inst, NULL);\n";
    src += "    CreateWindowExW(0, L\"BUTTON\", L\"Run Blocks\", WS_CHILD | WS_VISIBLE | BS_PUSHBUTTON, 24, 148, 140, 34, h, (HMENU)1001, inst, NULL);\n";
    src += "    return h;\n";
    src += "}\n\n";
    src += "static void vbc_destroy_panel(HWND h) { if (h && IsWindow(h)) DestroyWindow(h); }\n\n";
    src += "static YXG_PanelInfo g_panel = { \"" + EscapeCString(panelId) + "\", \"" + EscapeCString(panelTitle) + "\", \"" + EscapeCString(panelIcon) + "\" };\n\n";

    src += "YXG_EXPORT int YXG_RegisterPlugin(YXG_ExtensionApi* api, int apiVersion, void** context) {\n";
    src += "    if (apiVersion < YXG_API_VERSION) return 0;\n";
    src += "    g_api = api;\n";
    src += "    *context = (void*)1;\n";
    src += "    if (api && api->RegisterJSApi) api->RegisterJSApi((YXG_PluginContext*)*context, \"" + ns + "\", \"" + apiName + "\", vbc_api_" + apiName + ");\n";
    src += "    if (api && api->RegisterNativePanel) api->RegisterNativePanel((YXG_PluginContext*)*context, &g_panel, vbc_create_panel, vbc_destroy_panel);\n";
    src += "    if (api && api->LogInfo) api->LogInfo(L\"" + EscapeCString(opt.dllName) + " loaded\");\n";
    src += "    return 1;\n";
    src += "}\n\n";

    src += "YXG_EXPORT void YXG_UnregisterPlugin(void* context) {\n";
    src += "    (void)context;\n";
    src += "    if (g_api && g_api->UnregisterJSApi) g_api->UnregisterJSApi((YXG_PluginContext*)1, \"" + ns + "\", \"" + apiName + "\");\n";
    src += "    g_api = 0;\n";
    src += "}\n\n";

    src += "YXG_EXPORT const YXG_ExtensionInfo* YXG_GetExtensionInfo(void) {\n";
    src += "    static YXG_ExtensionInfo inf = { \"" + EscapeCString(opt.dllName) + "\", \"" + EscapeCString(opt.version) + "\", \"" + EscapeCString(opt.author) + "\", \"" + EscapeCString(desc) + "\" };\n";
    src += "    return &inf;\n";
    src += "}\n";

    return src;
}

