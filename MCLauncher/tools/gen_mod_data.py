# -*- coding: utf-8 -*-
"""Generate src/AddonNamesData.cpp from HMCL assets.

Source (read-only):
  D:/Desktop/HMCL-main/HMCL/src/main/resources/assets/addon/mod.csv
  D:/Desktop/HMCL-main/HMCL/src/main/resources/assets/lang/I18N_zh_Hans.properties

Output is a single embedded C++ raw string so the launcher DLL stays self-contained.
"""
from pathlib import Path

HMCL = Path(r"D:\Desktop\HMCL-main")
OUT = Path(__file__).resolve().parent.parent / "src" / "AddonNamesData.cpp"


def split_csv(line: str):
    """HMCL's escape-aware comma splitter (\\, \\n, \\\\, \\c ...)."""
    fields = []
    buf = []
    i = 0
    while i < len(line):
        c = line[i]
        if c == ",":
            fields.append("".join(buf))
            buf = []
            i += 1
            continue
        if c == "\\" and i + 1 < len(line):
            n = line[i + 1]
            mapping = {"0": "\0", "n": "\n", "r": "\r", "t": "\t", "\\": "\\", "c": ","}
            if n in mapping:
                buf.append(mapping[n])
                i += 2
                continue
            if n == "u" and i + 6 < len(line):
                try:
                    buf.append(chr(int(line[i + 2:i + 6], 16)))
                    i += 6
                    continue
                except ValueError:
                    pass
        buf.append(c)
        i += 1
    fields.append("".join(buf))
    return fields


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")


def main():
    csv_path = HMCL / "HMCL/src/main/resources/assets/addon/mod.csv"
    lang_path = HMCL / "HMCL/src/main/resources/assets/lang/I18N_zh_Hans.properties"

    rows = []
    for line in csv_path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        f = split_csv(line)
        if len(f) < 7:
            continue
        # fields: mcmodId, curseforgeId, modrinthId, mainName, subName, abbrName, modIds
        try:
            int(f[0])
        except ValueError:
            continue
        if not f[3]:
            continue
        rows.append("\t".join(esc(x) for x in f[:7]))

    cats = []
    for line in lang_path.read_text(encoding="utf-8-sig").splitlines():
        if line.startswith("modrinth.category."):
            key, _, value = line.partition("=")
            cats.append("\t".join((key[len("modrinth.category."):], value)))

    body = "# HMCL mod.csv fields: mcmodId, curseforgeId, modrinthId, mainName, subName, abbrName, modIds\n"
    body += "[mods]\n" + "\n".join(rows) + "\n[categories]\n" + "\n".join(cats) + "\n"

    assert "MCLDATA_END" not in body
    src = (
        "// Generated by tools/gen_mod_data.py — DO NOT EDIT BY HAND.\n"
        "// Data source: HMCL assets/addon/mod.csv + I18N_zh_Hans.properties (GPL-3.0-or-later).\n"
        "#include \"AddonRepo.h\"\n\n"
        "namespace addon {\nnamespace names {\n\n"
        "const char* const kData = R\"MCLDATA(" + body + ")MCLDATA\";\n\n"
        "} // namespace names\n} // namespace addon\n"
    )
    OUT.write_text(src, encoding="utf-8-sig")
    print(f"wrote {OUT} ({len(rows)} mods, {len(cats)} categories, {OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
